export type DocumentsTextKey = keyof typeof zh;

export function documentsText(language: string, key: DocumentsTextKey, params?: Record<string, string | number>): string {
  let s = (language === 'zh' ? zh : en)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useDocumentsText() {
  const { language } = useLanguage();
  return useCallback((key: DocumentsTextKey, params?: Record<string, string | number>) => documentsText(language, key, params), [language]);
}

export const DOCUMENTS_TEXT_KEYS = { zh: Object.keys(zh), en: Object.keys(en) };
